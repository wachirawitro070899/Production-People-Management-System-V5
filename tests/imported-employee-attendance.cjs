const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('app-v588.js','utf8');
const context={Intl,Date,Map};vm.createContext(context);
const date=source.slice(source.indexOf('function thaiDateKey('),source.indexOf('function thaiTime('));
const eligible=source.slice(source.indexOf('const employeeImportAttendanceDates='),source.indexOf('function thaiDateRange('));
vm.runInContext(date+eligible,context);
const check=context.employeeEligibleOnDate;
assert(!check({startDate:'',importedAt:'2026-10-20T07:00:00Z'},'2026-10-19'));
assert(check({startDate:'',importedAt:'2026-10-20T07:00:00Z'},'2026-10-20'));
assert(check({startDate:'2026-10-01',importedAt:'2026-10-20T07:00:00Z'},'2026-10-19'),'Actual employment date takes precedence when supplied');
assert(!check({importedAt:'2026-10-20T18:00:00Z'},'2026-10-20'),'Import date follows Bangkok time');
assert(check({importedAt:'2026-10-20T18:00:00Z'},'2026-10-21'));
assert(check({startDate:''},'2026-10-01'),'Legacy records without import metadata keep their existing behavior');
assert(!check({startDate:'2026-10-22'},'2026-10-21'));
assert(check({startDate:'2026-10-22'},'2026-10-22'));
assert(check({importedAt:'invalid'},'2026-10-01'),'Invalid optional metadata does not crash attendance');
const reconcile=source.slice(source.indexOf('function reconcileAutomaticAbsences('),source.indexOf('function reconcileAutomaticAbsences(')+5000);
assert(reconcile.includes('emp&&(!employeeEligibleOnDate(emp,d)'),'Existing automatic absences before the effective date are excluded during reconciliation');
console.log('Passed: imported employees are eligible from their Bangkok import date while employment date is missing, actual start dates override the fallback, earlier automatic absences are removed, and legacy records retain their behavior.');
